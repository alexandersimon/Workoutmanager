CREATE TABLE movement (
                          id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name        VARCHAR(150) NOT NULL,
                          name_key    VARCHAR(150) NOT NULL,
                          category    VARCHAR(30),
                          description VARCHAR(2000),
                          weighted    BOOLEAN NOT NULL DEFAULT FALSE,

                          CONSTRAINT uk_movement_name_key UNIQUE (name_key),

                          CONSTRAINT ck_movement_category CHECK (
                              category IN (
                                           'WEIGHTLIFTING',
                                           'GYMNASTICS',
                                           'MONOSTRUCTURAL',
                                           'STRONGMAN'
                                  )
                              )
);

CREATE TABLE workout (
                         id                         BIGINT PRIMARY KEY,
                         name                       VARCHAR(200) NOT NULL,
                         workout_type               VARCHAR(30),
                         workout_date               DATE,
                         description                VARCHAR(4000),
                         timecap_ms                 BIGINT,
                         rounds                     INTEGER NOT NULL,
                         rest_between_rounds_ms     BIGINT,

                         CONSTRAINT ck_workout_name CHECK (
                             CHAR_LENGTH(TRIM(name)) > 0
                             ),

                         CONSTRAINT ck_workout_rounds CHECK (rounds > 0),

                         CONSTRAINT ck_workout_timecap CHECK (
                             timecap_ms > 0
                             ),

                         CONSTRAINT ck_workout_rest CHECK (
                             rest_between_rounds_ms >= 0
                             )
);

CREATE TABLE scaling_option (
                                id                         BIGINT GENERATED BY DEFAULT AS IDENTITY
                                    PRIMARY KEY,
                                workout_id                 BIGINT NOT NULL,
                                scaling_level              VARCHAR(30) NOT NULL,
                                based_on_id                BIGINT,
                                rounds                     INTEGER,
                                rest_between_rounds_ms     BIGINT,

                                CONSTRAINT fk_scaling_workout
                                    FOREIGN KEY (workout_id)
                                        REFERENCES workout (id),

                                CONSTRAINT fk_scaling_base
                                    FOREIGN KEY (based_on_id)
                                        REFERENCES scaling_option (id),

                                CONSTRAINT uk_scaling_workout_level
                                    UNIQUE (workout_id, scaling_level),

                                CONSTRAINT ck_scaling_level CHECK (
                                    scaling_level IN ('RX', 'INTERMEDIATE', 'BEGINNER')
                                    ),

                                CONSTRAINT ck_scaling_rounds CHECK (rounds > 0),

                                CONSTRAINT ck_scaling_rest CHECK (
                                    rest_between_rounds_ms >= 0
                                    ),

                                CONSTRAINT ck_scaling_not_self CHECK (
                                    based_on_id <> id
                                    )
);

CREATE TABLE exercise (
                          id                  BIGINT GENERATED BY DEFAULT AS IDENTITY
                              PRIMARY KEY,
                          scaling_option_id   BIGINT NOT NULL,
                          movement_id         BIGINT NOT NULL,
                          exercise_position   INTEGER NOT NULL,
                          distance            DOUBLE PRECISION,
                          duration_ms         BIGINT,
                          weight_male         DOUBLE PRECISION,
                          weight_female       DOUBLE PRECISION,
                          weight_unit         VARCHAR(10),
                          notes               VARCHAR(2000),

                          CONSTRAINT fk_exercise_scaling
                              FOREIGN KEY (scaling_option_id)
                                  REFERENCES scaling_option (id),

                          CONSTRAINT fk_exercise_movement
                              FOREIGN KEY (movement_id)
                                  REFERENCES movement (id),

                          CONSTRAINT ck_exercise_position CHECK (
                              exercise_position >= 0
                              ),

                          CONSTRAINT ck_exercise_distance CHECK (distance > 0),

                          CONSTRAINT ck_exercise_duration CHECK (duration_ms > 0),

                          CONSTRAINT ck_exercise_weight_male CHECK (weight_male >= 0),

                          CONSTRAINT ck_exercise_weight_female CHECK (weight_female >= 0),

                          CONSTRAINT ck_exercise_weight_unit CHECK (
                              weight_unit IN ('KG', 'LBS')
                              ),

                          CONSTRAINT ck_exercise_weight_requires_unit CHECK (
                              (weight_male IS NULL AND weight_female IS NULL)
                                  OR weight_unit IS NOT NULL
                              )
);

CREATE TABLE exercise_repetition (
                                     exercise_id   BIGINT NOT NULL,
                                     rep_position  INTEGER NOT NULL,
                                     repetitions   INTEGER NOT NULL,

                                     PRIMARY KEY (exercise_id, rep_position),

                                     CONSTRAINT fk_repetition_exercise
                                         FOREIGN KEY (exercise_id)
                                             REFERENCES exercise (id),

                                     CONSTRAINT ck_repetition_position CHECK (rep_position >= 0),

                                     CONSTRAINT ck_repetition_value CHECK (repetitions > 0)
);

CREATE INDEX ix_exercise_scaling
    ON exercise (scaling_option_id);

CREATE INDEX ix_exercise_movement
    ON exercise (movement_id);

CREATE INDEX ix_scaling_base
    ON scaling_option (based_on_id);